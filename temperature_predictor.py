# IMPORT LIBRARIES

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

from sklearn.model_selection import train_test_split
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

print("Libraries import successfully:-")

# READ THE DATA SET

df =pd.read_csv("temperature_prediction.csv")
print(df.head(10))

print(df.tail())

# inspect the dataset

print("\nDataset Shape :")
print(df.shape)

print("\nColumn names :")
print(df.columns)

print("\nDataset information :")
df.info()

print("\nStatistical summary :")
print(df.describe())

# check data quality

print("Missing values :")
print(df.isnull().sum())

print("\nDuplicate rows :")
print(df.duplicated().sum())

# Humidity_pct vs Temperature_C

plt.figure(figsize=(8, 5))

plt.scatter(df["Humidity_pct"], df["Temperature_C"])

plt.xlabel("Humidity_pct")
plt.ylabel("Temperature_C")
plt.title("Humidity_pct vs Temperature_C")
plt.grid(True)

plt.show()

# Precipitation_mm  vs Temperature_C

plt.figure(figsize=(8, 5))

plt.scatter(df["Precipitation_mm"], df["Temperature_C"])

plt.xlabel("Precipitation_mm")
plt.ylabel("Temperature_C")
plt.title("Precipitation_mm  vs Temperature_C")
plt.grid(True)

plt.show()

# Wind_Speed_kmh  vs Temperature_C

plt.figure(figsize=(8, 5))

plt.scatter(df["Wind_Speed_kmh"], df["Temperature_C"])

plt.xlabel("Wind_Speed_kmh")
plt.ylabel("Temperature_C")
plt.title("Wind_Speed_kmh  vs Temperature_C")
plt.grid(True)

plt.show()

# Seprate Feature and Target

x = df[["Humidity_pct", "Precipitation_mm", "Wind_Speed_kmh"]]

y = df["Temperature_C"]

print("Features(X) : ")
print(x)

print("\nTarget(Y) : ")
print(y)

x_train, x_test, y_train, y_test = train_test_split(
    x,
    y,
    test_size=0.2,
    random_state=42
)

print("Training Samples : ", len(x_train))
print("Testing Samples : ", len(x_test))

# Building and Training
# Step :- 1 Create the Model

model = LinearRegression()

# Train the Model

model.fit(x_train, y_train)

# Inspect Learned Parameters

print("Coefficients : ")
print(model.coef_)

print("\nIntercept : ")
print(model.intercept_)

# Prediction
# STEP :- 1
# Predict the Test Data

y_pred = model.predict(x_test)

print("Actual Temperature : ")
print(y_test.values)

print("Predicted Temperature : ")
print(y_pred)

# STEP :- 2
# Compare Actual and Predicted Temperature

comparison = pd.DataFrame({
    "Actual Temperature": y_test.values,
    "Predicted Temperature": y_pred
})

print(comparison)

# MODEL EVALUATION
# STEP :- 1
# Mean Absolute Error(MAE)

mae = mean_absolute_error(y_test, y_pred)
print("Mean Absolute Error : ", mae)

mse = mean_squared_error(y_test, y_pred)
print("Mean Squared Error : ", mse)

rmse = np.sqrt(mse)

print("Root Mean Squared Error : ", rmse)

r2 = r2_score(y_test, y_pred)

print("R-squared : ", r2)

# predict marks for a new student
# iloc=indexing btata hai

new_temperature_data = pd.DataFrame({
    "Humidity_pct": [50],
    "Precipitation_mm": [50],
    "Wind_Speed_kmh": [50],
})

predicted_temperature = model.predict(new_temperature_data)

print("Humidity_pct :", new_temperature_data['Humidity_pct'].iloc[0])
print("Precipitation_mm :", new_temperature_data['Precipitation_mm'].iloc[0])
print("Wind_Speed_kmh :", new_temperature_data['Wind_Speed_kmh'].iloc[0])
print("Predicted Temperature : ", round (predicted_temperature[0], 2))

import joblib
import sklearn

# save the trained model
joblib.dump(model, "Temperature_predictor.pkl")

# check the installed scikit-learn version
print("scikit-learn version :", sklearn.__version__)

print("model saved successfully!")

